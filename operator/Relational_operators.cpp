/* Relational operators */
#include<stdio.h>
int main()
{
	int a,b;
	printf("Enter number1 : ");
	scanf("%d",&a);
	printf("Enter number2 : ");
	scanf("%d",&b);
	printf("\n a>b %d ",a>b);
	printf("\n a<b %d ",a<b);
	printf("\n a>=b %d ",a>=b);
	printf("\n a<=b %d ",a<=b);
	printf("\n a==b %d ",a==b);
	printf("\n a!=b %d ",a!=b);
	return 0;	
}
